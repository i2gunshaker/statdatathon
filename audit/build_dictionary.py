def main():
    tables=json.loads((OUT/"table_profiles.json").read_text())
    cols=json.loads((OUT/"column_profiles.json").read_text())
    inventory=list(csv.DictReader((OUT/"file_inventory.csv").open()))
    docs=json.loads((OUT/"documents.json").read_text())
    source=json.loads((OUT/"source_hashes.json").read_text())
    for row in inventory:
        if row["kind"]=="data" and row["path"]!="documentation/INDEX.csv":
            row["purpose"]=PURPOSE.get(family(row["path"]),"Метаданные")
        else:
            row["purpose"]={"table structure":"Описание колонок исходной формы; фактическая схема CSV может отличаться","reference book":"Справочник кодов; выбирать форму и год","blank form":"Пустая анкета с вопросами, единицами и частью кодировок","interviewer instruction":"Правила заполнения и переходы между вопросами"}.get(row["kind"],"Описание поставки или машиночитаемый перечень файлов")
    for name,meta in source.items():
        inventory.append({"path":name,"in_tar":False,"in_zip":False,"bytes":meta["bytes"],"kind":"project original",
                          "purpose":"Руководство каталога СНГ/API, не условия соревнования" if name.endswith("docx") else "Контейнер поставки; таблицы не следует загружать дважды"})
    csvout(OUT/"file_inventory.csv",inventory)
    groups=collections.defaultdict(list)
    for c in cols:
        f=family(c["path"])
        role,meaning=describe(f,c["column"])
        flags=[]
        if c["null_pct"]==100:flags.append("полностью пусто")
        elif c["null_pct"]>20:flags.append("пропуски >20%")
        if c["n_unique"]==1:flags.append("одно непустое значение")
        if c["leading_zero_rows"]:flags.append("ведущие нули")
        if c["whitespace_rows"]:flags.append("пробелы")
        if c.get("negative_rows"):flags.append("отрицательные значения")
        if c["column"]=="KVINT":flags.append("смысл не подтвержден")
        c.update({"family":f,"role":role,"description":meaning,"flags":"; ".join(flags)})
        groups[(f,c["column"])].append(c)
    csvout(OUT/"column_profiles.csv",cols)
    dump(OUT/"column_profiles.json",cols)
    (OUT/"DATA_DICTIONARY.md").write_text(dictionary_markdown(len(groups),len(cols)),encoding="utf-8")
    byfamily=collections.defaultdict(list)
    for t in tables:byfamily[family(t["path"])].append(t)
    changes=[]
    for f,ts in byfamily.items():
        for a,b in zip(ts,ts[1:]):
            sa,sb=set(a["columns"]),set(b["columns"])
            if a["columns"]!=b["columns"]:
                changes.append({"family":f,"from":a["path"],"to":b["path"],"added":sorted(sb-sa),"removed":sorted(sa-sb),"order_only":sa==sb})
    dump(OUT/"schema_changes.json",changes)
    csvout(OUT/"documents_index.csv",docs)
    print(len(groups),"dictionary entries",len(changes),"schema transitions",len(inventory),"inventory entries")


if __name__=="__main__":
    main()
